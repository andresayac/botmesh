#!/usr/bin/env node
/**
 * Regenerate the vendored request schemas in `src/specs/` from the official
 * OpenAPI documents. Run by hand when the upstream specs change; the tests
 * never fetch anything.
 *
 *   node scripts/vendor-openapi.mjs <twilio_api_v2010.json> <discord openapi.json> [twilioSha] [discordSha]
 *
 * Sources (both MIT; the Twilio document's `info.license` also says Apache-2.0):
 *   https://github.com/twilio/twilio-oai        spec/json/twilio_api_v2010.json
 *   https://github.com/discord/discord-api-spec specs/openapi.json
 *
 * Only the request body of the endpoints the providers call is kept, with
 * every `$ref` it reaches copied into `$defs` (descriptions and vendor
 * extensions are dropped to keep the files small).
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const [twilioPath, discordPath, twilioSha = 'unknown', discordSha = 'unknown'] = process.argv.slice(2)
if (!twilioPath || !discordPath) {
  process.stderr.write('usage: node scripts/vendor-openapi.mjs <twilio_api_v2010.json> <discord openapi.json> [twilioSha] [discordSha]\n')
  process.exit(1)
}

const DROP = new Set(['description', 'title', 'example', 'examples', 'externalDocs', 'deprecated', 'readOnly', 'writeOnly'])

/** Copy `node` without docs, collecting the component names it references. */
function clean(node, refs) {
  if (Array.isArray(node)) return node.map((n) => clean(n, refs))
  if (!node || typeof node !== 'object') return node
  const out = {}
  for (const [key, value] of Object.entries(node)) {
    if (DROP.has(key) || key.startsWith('x-')) continue
    if (key === '$ref' && typeof value === 'string') {
      const name = value.replace('#/components/schemas/', '')
      refs.add(name)
      out.$ref = `#/$defs/${name}`
      continue
    }
    // Property maps hold names, not keywords: keep every key there.
    if (key === 'properties') {
      out.properties = Object.fromEntries(Object.entries(value).map(([k, v]) => [k, clean(v, refs)]))
      continue
    }
    out[key] = clean(value, refs)
  }
  return out
}

function extract(doc, root) {
  const pending = new Set()
  const schema = clean(root, pending)
  const defs = {}
  while (pending.size) {
    const [name] = pending
    pending.delete(name)
    if (defs[name]) continue
    const target = doc.components.schemas[name]
    if (!target) throw new Error(`missing component ${name}`)
    const refs = new Set()
    defs[name] = clean(target, refs)
    for (const r of refs) if (!defs[r]) pending.add(r)
  }
  return Object.keys(defs).length ? { ...schema, $defs: Object.fromEntries(Object.entries(defs).sort(([a], [b]) => a.localeCompare(b))) } : schema
}

const twilio = JSON.parse(readFileSync(twilioPath, 'utf8'))
const discord = JSON.parse(readFileSync(discordPath, 'utf8'))

const twilioCreate = extract(twilio, twilio.paths['/2010-04-01/Accounts/{AccountSid}/Messages.json'].post.requestBody.content['application/x-www-form-urlencoded'].schema)
const discordCreate = extract(discord, discord.paths['/channels/{channel_id}/messages'].post.requestBody.content['application/json'].schema)
const discordEdit = extract(discord, discord.paths['/channels/{channel_id}/messages/{message_id}'].patch.requestBody.content['application/json'].schema)
const discordWebhook = extract(discord, discord.paths['/webhooks/{webhook_id}/{webhook_token}'].post.requestBody.content['application/json'].schema)

const header = (source, sha) => `/**
 * GENERATED by scripts/vendor-openapi.mjs — do not edit by hand.
 *
 * Request schemas extracted from ${source} at commit ${sha}
 * (MIT License; see src/specs/NOTICE.md). Descriptions and vendor extensions
 * were removed; \`$ref\`s point into \`$defs\`.
 */

import type { Schema } from '../sim/validate.js'
`

const emit = (name, value) => `\nexport const ${name}: Schema = ${JSON.stringify(value, null, 1)}\n`

const out = (file) => fileURLToPath(new URL(`../src/specs/${file}`, import.meta.url))
writeFileSync(out('twilio.ts'), header('twilio/twilio-oai spec/json/twilio_api_v2010.json', twilioSha) + emit('TWILIO_CREATE_MESSAGE_OPENAPI', twilioCreate))
writeFileSync(out('discord.ts'), header('discord/discord-api-spec specs/openapi.json', discordSha)
  + emit('DISCORD_MESSAGE_CREATE_OPENAPI', discordCreate)
  + emit('DISCORD_MESSAGE_EDIT_OPENAPI', discordEdit)
  + emit('DISCORD_WEBHOOK_EXECUTE_OPENAPI', discordWebhook))
process.stdout.write('wrote src/specs/twilio.ts and src/specs/discord.ts\n')
